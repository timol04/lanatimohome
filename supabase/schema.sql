-- Haushalt: wer darf überhaupt etwas sehen
create table if not exists public.household_members (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.household_members enable row level security;

create or replace function public.is_household()
returns boolean language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.household_members where user_id = auth.uid()); $$;

create table if not exists public.shopping_items (
  id uuid primary key default gen_random_uuid(),
  text text not null,                 -- Menü-Einträge: "[Menü] Name\nZutaten: ..."
  is_done boolean default false,
  quantity integer default 1,
  created_at timestamptz default now()
);

create table if not exists public.todos (
  id uuid primary key default gen_random_uuid(),
  text text not null,                 -- Fälligkeit im Text: "Aufgabe (bis 24.12.2026)"
  is_done boolean default false,
  created_at timestamptz default now()
);

create table if not exists public.notes (
  id uuid primary key default gen_random_uuid(),
  text text not null,
  author text not null,               -- E-Mail-Präfix, z.B. "timo.lanter"
  created_at timestamptz default now()
);

create table if not exists public.food_plan (
  id bigint generated by default as identity primary key,
  day text,                           -- "Montag" … "Sonntag"
  meal text,
  created_at timestamptz not null default now()
);

create table if not exists public.chores (
  id uuid primary key default gen_random_uuid(),
  text text not null,                 -- "Bad putzen (Lana) [Wöchentlich] (bis 05.01.2027)"
  is_done boolean not null default false,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.countdowns (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  date date not null,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.packages (
  id bigint generated by default as identity primary key,
  title text not null,
  courier text not null,              -- post | dhl | dpd | planzer | andere
  tracking_number text,
  is_delivered boolean default false,
  author text,
  created_at timestamptz default now()
);

create table if not exists public.wishlist (
  id bigint generated by default as identity primary key,
  title text not null,
  url text,
  price text,
  color text,
  image text,
  author text,
  is_purchased boolean default false,
  quantity integer default 1,
  prio integer default 0,             -- 0 = keine, 1 = hoch, 2 = mittel, 3 = niedrig
  created_at timestamptz default now()
);

