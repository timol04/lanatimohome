create table if not exists public.settings (
  id integer primary key default 1,
  household_names text not null
);

-- Zugriff: alles nur für den Haushalt
do $$
declare t text;
begin
  foreach t in array array['shopping_items','todos','notes','food_plan','chores','countdowns','packages','wishlist'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "Household full access" on public.%I', t);
    execute format('create policy "Household full access" on public.%I for all to authenticated using (public.is_household()) with check (public.is_household())', t);
  end loop;
end $$;

